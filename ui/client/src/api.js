async function call(method, url, body) {
  const res = await fetch(url, {
    method,
    headers: body === undefined ? {} : { "Content-Type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
    credentials: "same-origin",
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    // Session gone (expired, signed out elsewhere, server restarted): the server shows the sign-in page on reload.
    if (!url.startsWith("/api/auth/") && (res.status === 401 || data.code === "must_change")) location.reload();
    const err = new Error(data.error ?? `HTTP ${res.status}`);
    err.status = res.status;
    err.code = data.code;
    err.needsConfirm = !!data.needsConfirm;
    throw err;
  }
  return data;
}

